def _thumb_bl(src_rt, dst_rt):
    off = dst_rt - (src_rt + 4)
    if off < -(1 << 22) or off >= (1 << 22) or (off & 1):
        raise ValueError(f'Thumb BL out of range: {src_rt:#x}->{dst_rt:#x}')
    hi = 0xF000 | ((off >> 12) & 0x7FF)
    lo = 0xF800 | ((off >> 1) & 0x7FF)
    return struct.pack('<HH', hi, lo)

