def _lz77_literal_block(raw):
    if len(raw) >= (1 << 24):
        raise ValueError('LZ77 block too large')
    out = bytearray([0x10, len(raw) & 0xFF, (len(raw) >> 8) & 0xFF, (len(raw) >> 16) & 0xFF])
    for i in range(0, len(raw), 8):
        out.append(0)
        out += raw[i:i + 8]
    return bytes(out)


def _decode_4bpp_tile(tile):
    pixels = [[0] * 8 for _ in range(8)]
    for y in range(8):
        for xp in range(4):
            b = tile[y * 4 + xp]
            pixels[y][xp * 2] = b & 0x0F
            pixels[y][xp * 2 + 1] = b >> 4
    return pixels


def _pack_32x32_4bpp(pixels):
    out = bytearray(512)
    for ty in range(4):
        for tx in range(4):
            tile = (ty * 4 + tx) * 32
            for row in range(8):
                for col in range(8):
                    value = pixels[ty * 8 + row][tx * 8 + col] & 0x0F
                    bi = tile + row * 4 + col // 2
                    if col & 1:
                        out[bi] |= value << 4
                    else:
                        out[bi] |= value
    return bytes(out)


