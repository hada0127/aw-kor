def sha(raw):
    return hashlib.sha256(bytes(raw)).hexdigest()


def _align4(n):
    return (n + 3) & ~3


ARENA_START, ARENA_END = 0xA3D000, 0xAFF000  # dialogue_rewrite_apply relocated dialogue pool
GBA = 0x08000000


def _high_water(manifest, writes):
    """dialogue_rewrite_apply.Baseline.high_water over the live manifest/write log."""
    high = ARENA_START
    for m in manifest:
        if m.get('status') == 'relocated':
            high = max(high, int(m['new_addr'], 16) + int(m['new_len']))
    for w in writes:
        a, n = int(w[0]), int(w[1])
        if n and a < ARENA_END and a + n > ARENA_START:
            high = max(high, a + n)
    return high


def _tokens(payload):
    """(offset, raw) tokens: SJIS two-byte glyphs, 0x20 padding, single-byte controls."""
    out, i = [], 0
    data = bytes(payload)
    while i < len(data):
        b = data[i]
        if (0x81 <= b <= 0x9F or 0xE0 <= b <= 0xEF) and i + 1 < len(data):
            out.append((i, data[i:i + 2]))
            i += 2
        else:
            out.append((i, data[i:i + 1]))
            i += 1
    return out


def without_padding(payload):
    return b''.join(raw for _, raw in _tokens(payload) if raw != b' ')


def _text_runs(payload):
    """[(start, glyph_end)] maximal glyph/0x20 runs between controls (glyph_end skips padding)."""
    runs, start, end = [], None, None
    for off, raw in _tokens(payload):
        if len(raw) == 2 or raw == b' ':
            if start is None:
                start, end = off, off
            if len(raw) == 2:
                end = off + 2
            continue
        if start is not None:
            runs.append((start, end))
            start = None
    if start is not None:
        runs.append((start, end))
    return runs


def stage_messages(stage):
    return {s: e for s, e in MESSAGES.items() if e['stage'] == stage and e['kind'] != 'module'}


def _single(parts, label):
    if len(parts) != 1:
        raise AssertionError(f'B-pin native row has {len(parts)} fragments: {label}')
    return parts[0]


def expected_native(source):
    """Final in-place bytes (over the old message length) of a native message."""
    e = MESSAGES[source]
    old, new = bytes.fromhex(e['old']), bytes.fromhex(e['new'])
    out = bytearray(old)
    if set(e['old_fragments']) != set(e['fragments']):
        raise AssertionError(f'B-pin native owners changed: 0x{source:06X}')
    whole = [k for k, parts in e['old_fragments'].items() if parts == [[0, len(old)]]]
    if whole:
        if len(e['old_fragments']) != 1 or len(new) > len(old):
            raise AssertionError(f'B-pin whole native message invalid: 0x{source:06X}')
        return new + bytes(len(old) - len(new))
    for key, parts in e['old_fragments'].items():
        off, size = _single(parts, key)
        new_off, new_size = _single(e['fragments'][key], key)
        row = new[new_off:new_off + new_size]
        if not e['owner_texts'][key]:
            if bytes(old[off:off + size]) != row:
                raise AssertionError(f'B-pin native control row changed: {key}')
            continue
        if len(row) > size:
            raise AssertionError(f'B-pin native row exceeds its slot: {key}')
        out[off:off + size] = row + b' ' * (size - len(row))
    if without_padding(out) != without_padding(new):
        raise AssertionError(f'B-pin native layout differs from the reviewed tokens: 0x{source:06X}')
    return bytes(out)


def native_row_fragments(source, previous):
    """New row spans of a whole-message native owner, aligned by its control sequence.

    ``previous`` maps row key -> [offset, length] in the old payload (an earlier
    whole-message writer's ``source_line_fragments``).
    """
    e = MESSAGES[source]
    old, new = bytes.fromhex(e['old']), bytes.fromhex(e['new'])
    controls = lambda p: [raw for _, raw in _tokens(p) if len(raw) == 1 and raw != b' ']
    if controls(old) != controls(new):
        raise AssertionError(f'B-pin whole native message controls changed: 0x{source:06X}')
    old_runs, new_runs = _text_runs(old), _text_runs(new)
    if len(old_runs) != len(new_runs):
        raise AssertionError(f'B-pin whole native message rows changed: 0x{source:06X}')
    out = {}
    for key, (off, size) in previous.items():
        index = [i for i, (lo, hi) in enumerate(old_runs) if lo <= off < hi]
        if len(index) != 1 or off != old_runs[index[0]][0] and key != f'0x{source:06X}':
            raise AssertionError(f'B-pin whole native row is not a text run: {key}')
        lo, hi = new_runs[index[0]]
        out[key] = [lo, hi - lo]
    return out


def apply(stage, rom, original, manifest, writes, encode=None):
    """Write the ``stage`` messages; returns the number of messages written."""
    done = 0
    by_msg = {}
    for i, record in enumerate(manifest):
        if record.get('status') == 'relocated':
            by_msg.setdefault(int(record['msg'], 16), []).append(i)
    for source, e in sorted(stage_messages(stage).items()):
        old, new = bytes.fromhex(e['old']), bytes.fromhex(e['new'])
        rows = set(e['fragments'])
        if e['kind'] == 'native':
            if source in by_msg or e['target'] != source:
                raise AssertionError(f'B-pin native message is relocated: 0x{source:06X}')
            if bytes(rom[source:source + len(old)]) != old:
                raise AssertionError(f'B-pin stale native payload: 0x{source:06X}')
            final = expected_native(source)
            rom[source:source + len(old)] = final
            whole = [k for k, parts in e['old_fragments'].items() if parts == [[0, len(old)]]]
            if whole:
                prior = [w for w in writes if w[0] == source and len(w) > 8
                         and isinstance(w[8], dict) and w[8].get('source_line_fragments')]
                previous = prior[-1][8]['source_line_fragments'] if prior else {whole[0]: [0, len(old)]}
                writes.append([source, len(old), len(new), new.hex(), 0x00, None, None, NATIVE_WRITER,
                               {'source_address': source,
                                'source_line_fragments': native_row_fragments(source, previous)}])
            else:
                for key, parts in sorted(e['old_fragments'].items()):
                    if not e['owner_texts'][key]:
                        continue
                    off, size = parts[0]
                    new_off, new_size = e['fragments'][key][0]
                    row = new[new_off:new_off + new_size]
                    writes.append([source + off, size, len(row), row.hex(), 0x20,
                                   e['owner_texts'][key], 0, NATIVE_WRITER])
        else:
            index = by_msg.get(source, [])
            if len(index) != 1:
                raise AssertionError(f'B-pin relocation record missing/duplicate: 0x{source:06X}')
            record = manifest[index[0]]
            target = int(record['new_addr'], 16)
            if target != e.get('from', e['target']) or record['new_len'] != len(old):
                raise AssertionError(f'B-pin relocated target/length changed: 0x{source:06X}')
            if bytes(rom[target:target + len(old)]) != old:
                raise AssertionError(f'B-pin stale relocated payload: 0x{source:06X}')
            if 'from' in e:
                # Growth past the live allocation (fixB C1 review #1): a fresh
                # allocation at the aligned arena high water; the old one is
                # retired unchanged and every pointer site follows (as the W3 overlay).
                if len(new) <= _align4(len(old)):
                    raise AssertionError(f'B-pin relocation move is unnecessary: 0x{source:06X}')
                previous = target
                target = (_high_water(manifest, writes) + 3) & ~3
                lo, hi = target, target + len(new)
                if (target != e['target'] or hi > ARENA_END
                        or any(b != 0xFF for b in original[lo:hi]) or any(b != 0xFF for b in rom[lo:hi])
                        or any(w[0] < hi and lo < w[0] + w[1] for w in writes if w[1])):
                    raise AssertionError(f'B-pin fresh allocation changed/occupied: 0x{source:06X} at 0x{lo:06X}')
                writes.append([previous, len(old), len(old), old.hex(), None, None, None,
                               'dialogue-rewrite-retired-allocation'])
                rom[lo:hi] = new
                writes.append([target, len(new), len(new), new.hex(), None, None, None, WRITER,
                               {'source': source}])
                for site in sorted(int(x, 16) for x in record['ptr_sites']):
                    if struct.unpack_from('<I', rom, site)[0] != GBA + previous:
                        raise AssertionError(f'B-pin stale pointer 0x{site:06X}: 0x{source:06X}')
                    raw = struct.pack('<I', GBA + target)
                    rom[site:site + 4] = raw
                    writes.append([site, 4, 4, raw.hex(), None, None, None, 'dialogue-rewrite-pointer'])
                record['new_addr'] = f'0x{target:06X}'
            elif len(new) > _align4(len(old)):
                raise AssertionError(f'B-pin payload exceeds its allocation: 0x{source:06X}')
            elif len(new) > len(old):
                lo, hi = target + len(old), target + len(new)
                if any(w[0] < hi and lo < w[0] + w[1] for w in writes if w[1]):
                    raise AssertionError(f'B-pin allocation slack is owned: 0x{source:06X}')
                rom[target:target + len(new)] = new
                writes.append([target, len(new), len(new), new.hex(), None, None, None, WRITER,
                               {'source': source}])
            else:
                rom[target:target + len(old)] = new + bytes(len(old) - len(new))
                writes.append([target, len(old), len(new), new.hex(), 0x00, None, None, WRITER,
                               {'source': source}])
            tag = f'repoint:0x{source:06X}'
            bound = [i for i, w in enumerate(writes) if w[7] == tag]
            if len(bound) != 1:
                raise AssertionError(f'B-pin relocation binding missing/duplicate: {tag}')
            binding = writes[bound[0]]
            writes[bound[0]] = [target, len(new), len(new)] + binding[3:]
            record.update(new_len=len(new),
                          line_spans={k: v[0] for k, v in e['fragments'].items()},
                          source_line_fragments={k: [list(p) for p in v] for k, v in e['fragments'].items()},
                          source_fragment_joiners={k: list(e['joiners'].get(k, [])) for k in e['fragments']},
                          source_texts=dict(e['owner_texts']))
            record.pop('display_line_spans', None)
            record['rewrite'] = dict(batch=BATCH, review_ref=REVIEW_REF, before_sha256=sha(old),
                                     after_sha256=sha(new), previous_target=f'0x{e.get("from", target):06X}',
                                     previous_len=len(old), previous_status='relocated', bpin=True)
        owners = {int(k, 16) for k in rows}
        for w in writes:
            if (w[7] == 'dialogue-spacing-final-intent' and len(w) > 8
                    and w[8].get('source_address') in owners):
                w[7] = SUPERSEDED_INTENT
                w[8]['superseded_by'] = f'bpin-contract:0x{source:06X}'
        done += 1
    if stage == 'early':
        if encode is None:
            raise AssertionError('B-pin retained Help source needs the builder encoder')
        for address, (text, end, reviewed) in RETAINED.items():
            raw = bytes(encode(text, address))
            slot = bytes(rom[address:end])
            used = len(slot.rstrip(b'\0'))
            if raw.hex() != reviewed:
                raise AssertionError(f'B-pin retained Help source encoding changed: 0x{address:06X}')
            if len(raw) != used or slot[used:] != bytes(end - address - used):
                raise AssertionError(f'B-pin retained Help source size changed: 0x{address:06X}')
            rom[address:address + used] = raw
            writes.append([address, used, used, raw.hex(), None, None, None, RETAINED_WRITER])
    return done


def verify(rom, manifest):
    """Final (pre-ellipsis-compaction) state of every B-pin message."""
    relocated = {int(m['msg'], 16): m for m in manifest if m.get('status') == 'relocated'}
    for source, e in sorted(MESSAGES.items()):
        new = bytes.fromhex(e['new'])
        if e['kind'] == 'native':
            final = expected_native(source)
            if source in relocated or bytes(rom[source:source + len(final)]) != final:
                raise AssertionError(f'B-pin native final bytes changed: 0x{source:06X}')
            continue
        record = relocated.get(source)
        if record is None or int(record['new_addr'], 16) != e['target']:
            raise AssertionError(f'B-pin relocated message moved: 0x{source:06X}')
        target = e['target']
        if record['new_len'] != len(new) or bytes(rom[target:target + len(new)]) != new:
            raise AssertionError(f'B-pin relocated final bytes changed: 0x{source:06X}')
        if e['kind'] == 'relocated' and (record.get('source_texts') != e['owner_texts']
                                         or (record.get('rewrite') or {}).get('after_sha256') != sha(new)):
            raise AssertionError(f'B-pin relocated record changed: 0x{source:06X}')
    for address, (text, end, reviewed) in RETAINED.items():
        raw = bytes.fromhex(reviewed)
        if bytes(rom[address:end]) != raw + bytes(end - address - len(raw)):
            raise AssertionError(f'B-pin retained Help source changed: 0x{address:06X}')
    return len(MESSAGES)


def help_source_rows(rom):
    """Write the reviewed native Help rows and the D82218 retained source (test fixtures)."""
    for source, e in MESSAGES.items():
        if e['owner'] == 'd821f0_help' and e['kind'] == 'native':
            final = expected_native(source)
            rom[source:source + len(final)] = final
    for address, (text, end, reviewed) in RETAINED.items():
        raw = bytes.fromhex(reviewed)
        rom[address:end] = raw + bytes(end - address - len(raw))
    return rom


def bteam_approvals():
    """{0x%08X row: dict(from, to, ...)}: B-team rows whose reviewed wording this writer ships."""
    return {row: dict(baseline=b, to=t, message=m, approved=APPROVED, batch=BATCH, review_ref=REVIEW_REF)
            for row, (b, t, m) in BTEAM_APPROVALS.items()}


def text(source, row=None):
    """Reviewed owner text of ``row`` (default: the message's first text row)."""
    e = MESSAGES[source]
    if row is None:
        row = next(k for k in sorted(e['owner_texts']) if e['owner_texts'][k])
    return e['owner_texts'][row]
